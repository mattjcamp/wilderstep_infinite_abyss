#!/usr/bin/env node
/**
 * reindex-sprites — rebuild every module's `sprites/index.json` from
 * the PNGs currently on disk.
 *
 * Each module may ship art in `web/public/modules/<id>/sprites/<category>/`
 * (the base art lives in the Default module). The editor and game read
 * the per-module index.json, not the directories, because the static
 * build has no filesystem API at runtime. Run this after dropping PNGs
 * into a module's sprites folder.
 *
 * Usage:
 *   node scripts/reindex-sprites.mjs
 *   # or via npm:
 *   npm run reindex-sprites
 *
 * Safety: only writes `index.json` inside `public/modules/<id>/sprites/`;
 * skips hidden files and non-PNG entries; idempotent.
 */

import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const DEFAULT_MODULES_ROOT = path.resolve(__dirname, "..", "public", "modules");

export const SPRITE_INDEX_COMMENT =
  "Sprite catalog (generated by scripts/reindex-sprites.mjs). Each top-level key is a category folder under this module's sprites/ folder; each value is the list of PNG files in it, as paths relative to that folder (subfolders mirror the Tile Palette tag hierarchy, e.g. `house/chapel/door.png` under `town`). A sprite reference like `map/grass.png` resolves to the nearest module in the active module's chain (itself, its parents, then Default) whose index lists it.";

async function dirs(p) {
  try {
    return (await fs.readdir(p, { withFileTypes: true }))
      .filter((e) => e.isDirectory() && !e.name.startsWith("."))
      .map((e) => e.name)
      .sort();
  } catch (e) {
    if (e && e.code === "ENOENT") return [];
    throw e;
  }
}

/** Every PNG under `p`, recursively, as paths relative to `p` with "/"
 *  separators ("grass.png", "house/chapel/door.png"). Subfolders let the
 *  sprite folders mirror the Tile Palette tag hierarchy
 *  (tag "town:house:chapel" → sprites/town/house/chapel/). Hidden
 *  files/folders are skipped. Sorted for a stable index. */
export async function listPngsRecursive(p, prefix = "") {
  const out = [];
  for (const e of await fs.readdir(p, { withFileTypes: true })) {
    if (e.name.startsWith(".")) continue;
    if (e.isDirectory()) {
      out.push(...(await listPngsRecursive(path.join(p, e.name), `${prefix}${e.name}/`)));
    } else if (e.isFile() && e.name.toLowerCase().endsWith(".png")) {
      out.push(prefix + e.name);
    }
  }
  return prefix ? out : out.sort();
}

/** Rebuild one module's sprite index. Returns per-category counts, or
 *  null when the module has no sprites folder. Only rewrites index.json
 *  when its content actually changes. */
export async function reindexModuleSprites(moduleId, modulesRoot = DEFAULT_MODULES_ROOT) {
  const root = path.join(modulesRoot, moduleId, "sprites");
  const cats = await dirs(root);
  if (cats.length === 0) return null;
  const out = { _comment: SPRITE_INDEX_COMMENT, categories: {} };
  for (const cat of cats) {
    const files = await listPngsRecursive(path.join(root, cat));
    if (files.length > 0) out.categories[cat] = files; // skip empty folders
  }
  const next = JSON.stringify(out, null, 2) + "\n";
  const indexPath = path.join(root, "index.json");
  let prev = null;
  try {
    prev = await fs.readFile(indexPath, "utf8");
  } catch {
    // first index for this module
  }
  if (prev !== next) await fs.writeFile(indexPath, next);
  return Object.fromEntries(
    Object.entries(out.categories).map(([c, f]) => [c, f.length]),
  );
}

/** Rebuild the sprite index of every module under `modulesRoot`. */
export async function reindexAllSprites(modulesRoot = DEFAULT_MODULES_ROOT, log = console.log) {
  let total = 0;
  for (const id of await dirs(modulesRoot)) {
    const counts = await reindexModuleSprites(id, modulesRoot);
    if (!counts) continue;
    const n = Object.values(counts).reduce((a, b) => a + b, 0);
    total += n;
    log(`${id}: ${n} files`);
    for (const [c, k] of Object.entries(counts)) log(`  ${c}: ${k}`);
  }
  log(`reindex-sprites: ${total} files indexed.`);
  return total;
}

async function main() {
  await reindexAllSprites();
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((e) => {
    console.error(e);
    process.exit(1);
  });
}
